#ifndef STM32_IAP_CONFIG_H
#define STM32_IAP_CONFIG_H

#include "iap/iap.h"

#define STM32_IAP_FLASH_BASE 0x08000000u
#define STM32_IAP_FLASH_END 0x08100000u

#define STM32_IAP_BOOTLOADER_ADDRESS 0x08000000u
#define STM32_IAP_BOOTLOADER_SIZE 0x00020000u

#define STM32_IAP_SLOT_A_ADDRESS 0x08020000u
#define STM32_IAP_SLOT_B_ADDRESS 0x08060000u
#define STM32_IAP_SLOT_SIZE 0x00040000u
#define STM32_IAP_IMAGE_HEADER_SIZE 0x00000200u

#define STM32_IAP_CONTROL_A_ADDRESS 0x080A0000u
#define STM32_IAP_CONTROL_B_ADDRESS 0x080C0000u
#define STM32_IAP_CONTROL_SECTOR_SIZE 0x00020000u

#define STM32_IAP_RESERVED_ADDRESS 0x080E0000u
#define STM32_IAP_RESERVED_SIZE 0x00020000u

#define STM32_IAP_STAGING_ADDRESS 0x20008000u
#define STM32_IAP_STAGING_END 0x2001FF00u
#define STM32_IAP_STAGING_SIZE (STM32_IAP_STAGING_END - STM32_IAP_STAGING_ADDRESS)

#define STM32_IAP_TEST_CONTROL_ADDRESS 0x2001FF00u
#define STM32_IAP_TEST_CONTROL_SIZE 0x00000100u

#define STM32_IAP_MAX_BOOT_ATTEMPTS 3u

static inline void stm32_iap_slot_descriptors(iap_slot_desc_t slots[IAP_SLOT_COUNT])
{
    slots[IAP_SLOT_A].address = STM32_IAP_SLOT_A_ADDRESS;
    slots[IAP_SLOT_A].size = STM32_IAP_SLOT_SIZE;
    slots[IAP_SLOT_B].address = STM32_IAP_SLOT_B_ADDRESS;
    slots[IAP_SLOT_B].size = STM32_IAP_SLOT_SIZE;
}

#endif
